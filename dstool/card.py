"""The dataset card (README.md), generated from dataset.json and data/manifest.json."""

from __future__ import annotations

from dstool.common import PROTECTED_SPLITS, SPLITS, TRAINING_SPLITS, Config, load_json

SPLIT_PURPOSE = {
    "train": "training",
    "validation": "model selection during training",
    "test": "evaluation; never trained on",
    "holdout": "final, rarely-run evaluation; never trained on",
    "adversarial": "robustness: hostile, conflicting or malformed input; never trained on",
    "regression": "exact engine-behaviour pins that detect drift; never trained on",
}


def render(config: Config) -> str:
    manifest = load_json(config.path("data", "manifest.json"))
    card = config.raw["card"]
    lic = config.raw["license"]
    total = manifest["record_count"]
    size = "n<1K" if total < 1000 else "1K<n<10K"
    lines = [
        "---",
        f"pretty_name: {card['pretty_name']}",
        "license: other",
        f"license_name: {lic['name']}",
        f"license_link: {lic.get('file', 'LICENSE')}",
        "size_categories:",
        f"  - {size}",
        "tags:",
        *[f"  - {t}" for t in card["tags"]],
        "configs:",
        "  - config_name: default",
        "    data_files:",
        *[f"      - split: {s}\n        path: data/{s}.jsonl" for s in SPLITS],
        "---",
        "",
        "<!-- GENERATED by `python -m dstool card`; edit dataset.json, then regenerate. -->",
        "",
        f"# {config.raw['title']}",
        "",
        config.raw["summary"],
        "",
        f"Version **{manifest['version']}** ({manifest['release_date']}), {total} records, "
        f"records digest `{manifest['records_sha256'][:16]}…`.",
        "",
        "## Categories",
        "",
        "| category | " + " | ".join(SPLITS) + " | description |",
        "|---|" + "---|" * len(SPLITS) + "---|",
    ]
    for cat in config.raw["categories"]:
        counts = manifest["categories"][cat["id"]]
        lines.append(f"| {cat['title']} | " + " | ".join(str(counts[s]) for s in SPLITS) + f" | {cat['description']} |")
    lines.append("| **total** | " + " | ".join(f"**{manifest['splits'][s]}**" for s in SPLITS) + " | |")
    lines += [
        "",
        "## Splits",
        "",
        "| split | records | use |",
        "|---|---|---|",
        *[f"| `{s}` | {manifest['splits'][s]} | {SPLIT_PURPOSE[s]} |" for s in SPLITS],
        "",
        "- **Locked.** Each record's split is fixed in `splits.lock.json`, and a locked id never changes split "
        "or content. A change needs a new variant id; the old one is retired, never reused.",
        "- **Grouped by family.** All variants of a seed family share one split, so near-identical records "
        "cannot sit on both sides of a split boundary.",
        f"- **Protected.** {', '.join(PROTECTED_SPLITS)} are protected. The only training export "
        f"(`python -m dstool export --purpose training`) reads {' and '.join(TRAINING_SPLITS)} only and refuses "
        "any record that is protected, locked to a protected split, or carries the canary.",
        "",
        "## Record format",
        "",
        "Each line of `data/<split>.jsonl` is one `blux.dataset-record` v1 (`schemas/record.v1.schema.json`):",
        "",
        "```text",
        "record_id   <prefix>:<family>:<variant>, immutable",
        "category    one of the categories above",
        "split       one of the six splits",
        "task        {instruction}: the request in plain language",
        "input       what the engine was given",
        "expected    what the pinned engine actually produced (an artifact, a result, or an error)",
        "provenance  origin, authors, licence, seed file + hash, generator, engines (with commits), review",
        "quality     score, threshold and components",
        "hashes      input, expected and content SHA-256",
        "canary      the dataset canary on protected records, else null",
        "```",
        "",
        card["record_format"],
        "",
        "## Provenance and licence",
        "",
        f"- Licence: **{lic['name']}** (`{lic['spdx']}`, see `{lic.get('file', 'LICENSE')}`). Every record "
        "repeats it in `provenance.license`.",
        "- Every record is generated by running the pinned engines on an authored seed:",
        *[f"  - {e['package']} {e['version']} at `{e['commit'][:12]}`" for e in manifest["engines"]],
        "- Seeds are synthetic and written for this dataset (`origin: synthetic-authored`).",
        "- Imported material (`python -m dstool import`) is written with `review: pending`. The build skips it "
        "until a named reviewer promotes it, and imports can never target holdout, adversarial or regression.",
        "- No private user or project data. A privacy scan gates every record: personal e-mail, phone numbers, "
        "non-documentation IPs, home paths, credentials, and an untracked `.private-terms` deny list.",
        "- No hidden reasoning. Records hold explicit inputs and engine outputs only. A scan rejects keys and "
        "markers that name model reasoning (`thought`, `chain_of_thought`, `scratchpad`, `<thinking>` …). The "
        "only exception is an adversarial request that the engine rejected.",
        "",
        "## Contamination controls",
        "",
        "- **Exact duplicates.** Records with the same normalized text (lower-cased, numbers folded) are "
        "dropped within a split and are a build failure across splits.",
        f"- **Near duplicates.** A Jaccard similarity of 4-token shingles of at least "
        f"{config.raw['near_duplicate_threshold']} between records of different splits fails the build. "
        "`data/contamination.json` lists each protected record's nearest record in another split.",
        "- **Families.** A family spanning two splits fails the build.",
        f"- **Canary.** Every protected record carries the canary string `{config.canary}`. If it appears in a "
        "training corpus, that corpus contains this dataset's protected records.",
        "",
        "## Quality",
        "",
        "- **Gates.** Every record is schema-valid and reproducible (two engine runs agree), and passes the "
        "privacy and hidden-reasoning scans.",
        "- **Score.** The score is the mean of these components: instruction length, grounding (the "
        "instruction names something in the input), evidence where applicable, informative output, and "
        "distinctness from other families in its split.",
        f"- **Threshold.** Records below {config.raw['quality_threshold']} are excluded and listed in "
        "`data/manifest.json`.",
        "",
        "## Reproducing and validating",
        "",
        "How the dataset is built and checked is documented in `docs/ENGINEERING.md`.",
        "",
        "```bash",
        "pip install -r requirements.txt            # the pinned engines and jsonschema",
        "python -m dstool build --check             # regenerate everything; byte-identical or exit 1",
        "python -m dstool validate                  # records, hashes, lock, contamination, manifest",
        "python -m dstool export --purpose training -o train.jsonl",
        "python -m pytest",
        "```",
        "",
        "## Intended use",
        "",
        *[f"- {u}" for u in card["intended_use"]],
        "",
        "## Out of scope",
        "",
        *[f"- {u}" for u in card["out_of_scope"]],
        "",
        "## Limitations",
        "",
        *[f"- {u}" for u in card["limitations"]],
        "",
        "## Legacy",
        "",
        "The frozen 1.0 drift-detection fixtures are in `legacy/` (docs/LEGACY.md), still checked in CI.",
        "",
    ]
    return "\n".join(lines)
